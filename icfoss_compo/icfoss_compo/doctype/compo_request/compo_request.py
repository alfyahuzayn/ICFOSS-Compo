"""
Compo Request: "I want one compensatory off for my extra hours."

The employee only chooses the dates. The SERVER fills the days table:
the oldest available days are taken until they add up to exactly 8:00 (Compo Settings).
Whatever is left on a day stays available for the next request (carry-over).

Rules enforced here:
  * employee must not be excluded from compensatory off
  * date range: not in the future, inside the allowed window (same month unless Carry-Over Months > 0)
  * at least 8:00 available, otherwise the request cannot even be saved
  * monthly cap shared with the standard Compensatory Leave Request (icfoss_compo.limits)
  * the days table can never be edited by hand
"""
import frappe
from frappe import _
from frappe.model.document import Document
from frappe.utils import cint, formatdate, get_first_day, getdate, nowdate

from icfoss_compo.availability import get_available_days, get_settings, hhmm
from icfoss_compo.limits import validate_monthly_cap


class CompoRequest(Document):
    def validate(self):
        self.validate_employee()
        self.validate_dates()

        # Only (re)build and (re)check the quota when the request is new or its inputs changed.
        # Later saves - e.g. workflow approvals - must not shuffle the days or re-run the cap.
        rebuild = self.docstatus == 0 and (self.is_new() or self.inputs_changed())
        if rebuild:
            self.build_days()
        else:
            self.check_days_untouched()

        self.validate_minimum()

        if rebuild:
            validate_monthly_cap(
                self.employee,
                self.cap_month,
                requested=self.leave_days or 1,
                exclude=(self.doctype, self.name),
            )

    # ------------------------------------------------------------------

    def validate_employee(self):
        if frappe.db.get_value("Employee", self.employee, "custom_exclude_from_compo"):
            frappe.throw(_("{0} is excluded from compensatory off / extra hours.").format(self.employee))

    def validate_dates(self):
        from_date, to_date = getdate(self.from_date), getdate(self.to_date)
        if from_date > to_date:
            frappe.throw(_("From Date cannot be after To Date."))
        if to_date > getdate(nowdate()):
            frappe.throw(_("To Date cannot be in the future."))

        carry = get_settings().carry_over_months
        months = (to_date.year - from_date.year) * 12 + (to_date.month - from_date.month)
        if months > carry:
            if carry == 0:
                frappe.throw(_("From Date and To Date must be in the same month."))
            frappe.throw(_("The date range can reach back at most {0} month(s).").format(carry))

    def inputs_changed(self):
        before = self.get_doc_before_save()
        if not before:
            return True
        return (
            before.employee != self.employee
            or getdate(before.from_date) != getdate(self.from_date)
            or getdate(before.to_date) != getdate(self.to_date)
        )

    def build_days(self):
        result = get_available_days(
            self.employee, self.from_date, self.to_date, exclude_request=self.name, lock=True
        )
        self.set("days", [])
        for row in result.rows:
            self.append("days", row)

        self.total_available_minutes = result.total_available
        self.allocated_minutes = result.allocated
        self.leave_days = 1

        # the month this leave counts against = month of the latest work day it uses
        latest = max((getdate(r["log_date"]) for r in result.rows), default=getdate(self.to_date))
        self.cap_month = get_first_day(latest)

    def check_days_untouched(self):
        before = self.get_doc_before_save()
        if not before:
            return

        def signature(doc):
            return sorted((d.log, cint(d.use_minutes)) for d in doc.get("days"))

        if signature(before) != signature(self):
            frappe.throw(_("The days table is generated by the system and cannot be edited."))

    def validate_minimum(self):
        needed = get_settings().minutes_per_leave
        if cint(self.allocated_minutes) < needed:
            frappe.throw(
                _(
                    "A compensatory off needs {0} of extra hours. You have {1} available "
                    "between {2} and {3}."
                ).format(
                    hhmm(needed),
                    hhmm(self.total_available_minutes),
                    formatdate(self.from_date),
                    formatdate(self.to_date),
                ),
                title=_("Not enough extra hours"),
            )


@frappe.whitelist()
def preview_days(employee, from_date, to_date, request_name=None):
    """Used by the form to show the days before saving. Same calculation as the server uses on save."""
    # respects User Permissions: an employee can only look at their own hours
    frappe.has_permission("Employee", "read", employee, throw=True)

    result = get_available_days(employee, from_date, to_date, exclude_request=request_name)
    return {
        "rows": [dict(r, log_date=str(r["log_date"])) for r in result.rows],
        "total_available": result.total_available,
        "allocated": result.allocated,
        "required": result.required,
    }